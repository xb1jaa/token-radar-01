// Token Radar's model: one snapshot of the protocol universe in, one ranked board out.
//
// The board ranks standalone protocols that record no token yet. The watchlist is the floor: every
// slug on it is ranked. Below the floor, the early radar adds pre-token protocols by TVL — but only
// standalone candidates, under the same rule the house used to draw the watchlist: no exchange, no
// versioned pool (a name ending in V2, v2, 2.0 and the like), no bridge, liquid-staking or restaking
// product, no name carrying a whole word wrapped, staked or staking, and no name beginning with an
// exchange's name. Those are products of a token that already trades, not a launch still to come.
//
// Implied value follows only from the snapshot's own figures, one function for every protocol:
//
//   multiple   = clamp(0.85 * (1e9 / tvl_usd)^0.12, 0.18, 0.85)
//                A token's value per dollar of TVL falls as the protocol grows: a small protocol's
//                launch is priced on its upside, a giant's on its size. At $50M TVL the multiple is
//                0.85; at $1B it is 0.85; at $10B it is about 0.65; at $50B about 0.53.
//   growth     = clamp(change_7d, -80, 150) per cent
//   growthMult = 1 + (growth / 100) * GROWTH_WEIGHT
//   maturity   = 0.55 + min(age_days, 1460) / 1460 * 0.45   (age unknown: 365 days)
//                A protocol that has run longer with no token has survived longer without one, so its
//                launch, when it comes, carries more weight. The factor never drops below 0.55: youth
//                is not worthlessness, it is less evidence.
//   breadth    = 1 + 0.02 * min(chains - 1, 4)
//                A protocol live on more chains reaches more users; the factor is capped at 1.08 so
//                chain-counting never outruns TVL, growth and age.
//   implied    = max(1, round(tvl_usd * multiple * growthMult * maturity * breadth))
//
// No protocol name is ever special-cased: the same function scores every row. The dashboard states
// the formula and recomputes every row from the same figures, so the page and board.json agree.

